import assert from 'node:assert/strict'
import {chromium} from 'playwright'
import {existsSync,mkdirSync} from 'node:fs'
import {fileURLToPath} from 'node:url'
import {resolve} from 'node:path'

const base=process.env.TEST_BASE_URL || 'http://127.0.0.1:5000'
const executablePath=process.env.CHROME_PATH || ['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync)
const browser=await chromium.launch({headless:true,...(executablePath?{executablePath}:{})})
const shots=resolve(fileURLToPath(new URL('../..',import.meta.url)),'.runtime/screenshots')
mkdirSync(shots,{recursive:true})
const context=await browser.newContext({viewport:{width:958,height:875}})
const page=await context.newPage(),errors=[]
page.on('pageerror',e=>errors.push(e.message))
page.on('response',r=>{if(r.url().includes('/api/')&&r.status()>=500)errors.push(`${r.status()} ${r.url()}`)})
try{
  const login=await context.request.post(base+'/api/login',{data:{username:'analyst1',password:'123456'}})
  assert.equal(login.status(),200)
  const {token,user}=(await login.json()).data
  await context.addInitScript(({token,user})=>{localStorage.setItem('risk_alert_token',token);localStorage.setItem('risk_alert_user',JSON.stringify(user))},{token,user})
  await page.goto(base+'/')
  await page.locator('.work-queue button').first().waitFor()
  await page.locator('.single-event').waitFor()
  assert.equal(await page.locator('.brand small').count(),0)
  await page.getByRole('link',{name:'证据链浏览',exact:true}).click()
  await page.locator('.subject-list button').first().waitFor()
  await page.locator('.event-list button').first().waitFor()
  assert.ok(await page.locator('.event-list button').count()>1)
  await page.locator('.event-list button').nth(1).click()
  await page.getByRole('heading',{name:'证据时间轴',exact:true}).waitFor()
  await page.waitForLoadState('networkidle')
  await page.screenshot({path:resolve(shots,'evidence-regions-958.png'),fullPage:true})
  await page.getByText('按人员',{exact:true}).click()
  await page.getByPlaceholder('人员编号，支持部分输入').fill('P0277')
  await page.getByPlaceholder('人员编号，支持部分输入').press('Enter')
  await page.waitForFunction(()=>document.querySelectorAll('.subject-list button').length===1 && document.querySelector('.subject-list button')?.textContent.includes('P0277'))
  await page.waitForFunction(()=>document.querySelectorAll('.event-list button').length===3)
  assert.equal(await page.locator('.event-list button').count(),3)
  await page.screenshot({path:resolve(shots,'evidence-person-958.png'),fullPage:true})
  await page.goto(base+'/evidence?scope=area&area_id=A02&date=2026-11-24')
  await page.locator('.event-list button').first().waitFor()
  for(const text of await page.locator('.event-list button').allTextContents())assert.ok(text.includes('2026-11-24'))
  await page.goto(base+'/people')
  await page.locator('.recommend-list button').first().waitFor()
  assert.equal(await page.locator('.recommend-list button').count(),3)
  await page.locator('.recommend-list button').first().click()
  await page.waitForFunction(()=>document.querySelector('.person-detail .mono')?.textContent.includes('P0277'))
  await page.getByPlaceholder('人员编号，支持部分输入，如 P001').fill('P001')
  await page.getByPlaceholder('人员编号，支持部分输入，如 P001').press('Enter')
  await page.waitForFunction(()=>[...document.querySelectorAll('.people-workspace .el-table__body tbody tr')].some(r=>r.textContent.includes('P001')))
  await page.getByPlaceholder('人员编号，支持部分输入，如 P001').fill('NOT_A_PERSON')
  await page.getByPlaceholder('人员编号，支持部分输入，如 P001').press('Enter')
  await page.locator('.empty-help').waitFor()
  assert.equal(await page.locator('.person-detail').count(),0)
  await page.getByRole('button',{name:'清空搜索',exact:true}).click()
  await page.locator('.person-detail').waitFor()
  await page.waitForLoadState('networkidle')
  await page.screenshot({path:resolve(shots,'people-recommendations-958.png'),fullPage:true})
  await page.goto(base+'/risk-map')
  await page.locator('.map-range .el-select').waitFor()
  await page.waitForLoadState('networkidle')
  await page.locator('.map-range .el-select').click()
  await page.getByRole('option',{name:'2026-11-05 10:00:00',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.selection-panel')?.textContent.includes('暂无消费活动'))
  assert.ok((await page.locator('.selection-panel').textContent()).includes('无需人为补造记录'))
  await page.screenshot({path:resolve(shots,'map-no-activity-958.png'),fullPage:true})
  await page.setViewportSize({width:390,height:844})
  for(const path of ['/people','/evidence?scope=person&person_id=P0277']){
    await page.goto(base+path)
    await page.waitForLoadState('networkidle')
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2),false,`overflow: ${path}`)
    await page.screenshot({path:resolve(shots,path.startsWith('/people')?'people-recommendations-mobile.png':'evidence-mobile.png'),fullPage:true})
  }
  assert.deepEqual(errors,[])
  console.log('PASS: region/person evidence browsing, event selection, date scope, peak recommendations, partial search, empty recovery, quiet-vs-missing states, branding, 958px and 390px layout')
}finally{await browser.close()}
