const page=await context.newPage()
page.on('pageerror',e=>errors.push(e.message))
page.on('response',r=>{if(r.url().includes('/api/')&&r.status()>=500)errors.push(`${r.status()} ${r.url()}`)})
async function login(username){
  await page.goto(base+'/login')
  await page.getByPlaceholder('如 analyst1').fill(username)
  await page.locator('input[type=password]').fill('123456')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.waitForURL(base+'/')
}
async function api(path,options={}){
  return page.evaluate(async({path,options})=>{
    const r=await fetch(path,{...options,headers:{'Content-Type':'application/json',Authorization:'Bearer '+localStorage.getItem('risk_alert_token'),...options.headers}})
    return {status:r.status,...await r.json()}
  },{path,options})
}
